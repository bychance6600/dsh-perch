/** 词 → 归一后的词；表里没有就原样返回。 */
export function expandToken(t) {
  const s = String(t ?? '').trim().toLowerCase()
  if (!s) return ''
  return SYNONYMS.get(s) ?? s
}

/** 按长度从长到短匹配，避免「不开心」先被「开心」吃掉。 */
export const SYNONYM_KEYS = [...SYNONYMS.keys()].sort((a, b) => b.length - a.length || a.localeCompare(b))
